import fs from 'node:fs';
import path from 'node:path';
import {parse as yaml} from 'yaml';
import {stringify as toml} from 'smol-toml';
import {ROOT,walk,readJSON,block,select} from './source.mjs';
const generated = '<!-- Generated by AgentKit Engineer; edit canonical source. -->\n';
export function render(packs=['core'], agents=['codex','claude'], target=ROOT) {
  const chosen=select(packs,agents), out=new Map();
  const add=(name,data,type='file')=>out.set(name,{type, data:Buffer.isBuffer(data)?data:Buffer.from(data)});
  const instruction=fs.readFileSync(path.join(ROOT,'kit/project.md'),'utf8');
  const skillNames=[...new Set(chosen.packs.flatMap(p=>chosen.catalog[p]))];
  for (const host of chosen.agents) {
    const skillRoot=host==='codex'?'.agents/skills':'.claude/skills';
    add(host==='codex'?'AGENTS.md':'CLAUDE.md',block(generated+instruction),'block');
    add(`${skillRoot}/package.json`,fs.readFileSync(path.join(ROOT,'skills/package.json')));
    for (const name of [...skillNames,'common']) {
      const src=path.join(ROOT,'skills',name);
      for (const f of walk(src)) {
        let content=fs.readFileSync(f);
        if(f.endsWith('.md')) {
          const text=content.toString(),front=text.match(/^---\n[\s\S]*?\n---\n/);
          content=Buffer.from(front?front[0]+generated+text.slice(front[0].length):generated+text);
        }
        add(`${skillRoot}/${name}/${path.relative(src,f).split(path.sep).join('/')}`,content);
      }
    }
    for (const agent of readJSON(path.join(ROOT,'kit/agents.json')).filter(a=>chosen.packs.includes(a.pack))) {
      const source=fs.readFileSync(path.join(ROOT,`agents/${agent.name}.md`),'utf8');
      const match=source.match(/^---\n([\s\S]*?)\n---\n/), meta=yaml(match[1]);
      const body=source.slice(match[0].length).trim();
      const readTools=(agent.tools||['Read','Grep','Glob']).join(', ');
      if (host==='claude') add(`.claude/agents/${agent.name}.md`,source.replace(/\n---\n/,`\n${agent.readOnly?'tools: '+readTools+'\n':''}---\n${generated}`));
      else add(`.codex/agents/${agent.name}.toml`,'# Generated by AgentKit Engineer\n'+toml({name:agent.name,description:meta.description,...(agent.readOnly?{sandbox_mode:'read-only'}:{}),developer_instructions:body}));
    }
    for (const f of walk(path.join(ROOT,'workflows'))) add(`.agentkit/workflows/${path.basename(f)}`,fs.readFileSync(f));
    for (const f of walk(path.join(ROOT,'hooks'))) if(f.endsWith('.cjs')) add(`.agentkit/hooks/${path.basename(f)}`,fs.readFileSync(f));
    // Find the installed root from any project subdirectory; no shell-specific variables.
    const loader="let p=process.cwd(),f=require('node:fs'),j=require('node:path');while(!f.existsSync(j.join(p,'.agentkit/hooks/adapter.cjs'))){let q=j.dirname(p);if(q===p)process.exit(0);p=q;}process.argv=['node','adapter','HOST','MODE'];require(j.join(p,'.agentkit/hooks/adapter.cjs'));";
    const command=mode=>'node -e "'+loader.replace('HOST',host).replace('MODE',mode)+'"';
    const hooks={hooks:{PreToolUse:[{matcher:'Bash',hooks:[{type:'command',command:command('search')}]}],PostToolUse:[{matcher:'Write|Edit|apply_patch',hooks:[{type:'command',command:command('modularization')}]}]}};
    add(host==='codex'?'.codex/hooks.json':'.claude/settings.json',JSON.stringify(hooks,null,2)+'\n','json');
    if(host==='codex') add('.codex/config.toml','# agentkit:begin\n# AgentKit Engineer agents load from .codex/agents; model inherits the session.\n# Optional MCP: see .agentkit/templates/codex-mcp.toml.example\n# agentkit:end\n','toml-block');
    else {
      add('.mcp.json',JSON.stringify({mcpServers:{}},null,2)+'\n','json');
      for(const c of readJSON(path.join(ROOT,'kit/commands.json')).filter(c=>chosen.packs.includes(c.pack))) {
        add(`.claude/commands/${c.alias}.md`,`---\ndescription: "AgentKit ${c.workflow}"\n${c.argumentHint?`argument-hint: ${JSON.stringify(c.argumentHint)}\n`:""}---\n\n${generated}Use the ${c.workflow} skill. Mode arguments: ${c.arguments || '(default)'}.\nUser request: $ARGUMENTS\n`);
      }
    }
  }
  for(const f of walk(path.join(ROOT,'templates'))) add(`.agentkit/templates/${path.relative(path.join(ROOT,'templates'),f).split(path.sep).join('/')}`,fs.readFileSync(f));
  return {files:out, packs:chosen.packs,agents:chosen.agents};
}
